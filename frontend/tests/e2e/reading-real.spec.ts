import { test, expect, type Page } from '@playwright/test'
import { readFileSync, appendFileSync } from 'node:fs'
test.use({ trace: 'off', screenshot: 'off', video: 'off' })
test.setTimeout(90_000)
async function selectSmall(page: Page) {
  await expect(page.locator('.article-body')).toBeVisible()
  await page.locator('.article-body [data-sentence]').first().evaluate(element => {
    element.scrollIntoView({block:'center'});const range = document.createRange(); range.setStart(element.firstChild!, 6); range.setEnd(element.firstChild!, 11)
    const selection = window.getSelection()!; selection.removeAllRanges(); selection.addRange(range); document.dispatchEvent(new Event('selectionchange'))
  })
  await page.getByRole('button', { name: '查询选中单词：small', exact: true }).click()
}
async function signIn(page: Page, actor: { username: string; password: string }) {
  await page.goto('/login')
  await page.getByLabel('用户名', { exact: true }).fill(actor.username)
  await page.getByLabel('密码', { exact: true }).fill(actor.password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login(?:\?|$)/)
}
test('real administrator publishes a draft and learner starts the stored article', async ({ browser, page }) => {
  test.skip(process.env.E2E_READING_REAL !== '1', 'Requires dedicated MySQL/test Redis reading backend and recorded local fixtures')
  const actors = JSON.parse(readFileSync('../.tool-cache/phase-2/browser-actors.json', 'utf8').replace(/^\uFEFF/, '')) as Record<'admin' | 'learner' | 'other', { username: string; password: string }>
  await signIn(page, actors.admin)
  await expect(page).toHaveURL(/\/admin$/)
  await page.getByRole('link', { name: '文章管理', exact: true }).click()
  await page.getByRole('link', { name: '创建文章', exact: true }).click()
  const title = `A fresh page ${Date.now()}`
  await page.getByLabel('英文标题', { exact: true }).fill(title)
  await page.getByLabel('中文标题', { exact: true }).fill('新的一页')
  await page.getByLabel('简介', { exact: true }).fill('A small reading integration exercise.')
  await page.getByLabel('正文', { exact: true }).fill('Every small step matters. We learn by trying again.')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/articles\/[0-9]+\/edit$/)
  const id = page.url().match(/articles\/([0-9]+)\//)![1]!
  appendFileSync('../.tool-cache/phase-2/browser-article-ids.txt', `${id}\n`)
  await page.getByRole('button', { name: '发布草稿', exact: true }).click()
  await page.getByRole('button', { name: '确认发布', exact: true }).click()
  await expect(page.getByRole('button', { name: '下架文章', exact: true })).toBeVisible()
  const context = await browser.newContext({ viewport: page.viewportSize() ?? undefined })
  const otherContext = await browser.newContext({ viewport: page.viewportSize() ?? undefined })
  try {
    const learner = await context.newPage()
    await signIn(learner, actors.learner)
    await expect(learner.getByRole('heading', { name: 'Lingua Loop', exact: true })).toBeVisible()
    const opened = learner.waitForResponse(response => response.url().endsWith(`/reading/articles/${id}/start`) && response.request().method() === 'POST')
    await learner.goto(`/reading/${id}`)
    const oldVersion = String((await (await opened).json()).version.id)
    await expect(learner.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await expect(learner.locator('.article-body')).toContainText('Every small step matters.')
    await learner.getByRole('button', { name: '标记为已读', exact: true }).click()
    await expect(learner.getByText('进度已保存', { exact: true })).toBeVisible()
    await learner.reload()
    await expect(learner.locator('.article-body')).toContainText('Every small step matters.')
    await expect(learner.getByRole('button', { name: '已读完', exact: true })).toBeDisabled()
    await learner.getByRole('button', { name: '用户菜单', exact: true }).click()
    await learner.getByRole('button', { name: '退出登录', exact: true }).click()
    await expect(learner).toHaveURL(/\/login$/); await signIn(learner, actors.learner)
    await learner.goto(`/reading/${id}?version=${oldVersion}`)
    await expect(learner.getByRole('button', { name: '已读完', exact: true })).toBeDisabled()
    await selectSmall(learner)
    const collected = learner.waitForResponse(response => response.url().endsWith('/vocabulary/words') && response.request().method() === 'POST')
    await learner.getByRole('dialog').getByRole('button', { name: /^(收藏生词|记录此处来源|恢复收藏)$/ }).click()
    const wordId = String((await (await collected).json()).word.id)
    await expect(learner.getByRole('dialog').getByRole('button', { name: '已收藏', exact: true })).toBeDisabled()
    await learner.keyboard.press('Escape'); await learner.goto('/notebook')
    await learner.getByRole('button', { name: 'small', exact: true }).click()
    await expect(learner.locator(`a[href^="/reading/${id}?version=${oldVersion}"]`)).toBeVisible()
    const other = await otherContext.newPage(); await signIn(other, actors.other); await other.goto('/notebook')
    await expect(other.getByRole('heading', { name: '还没有收藏的生词', exact: true })).toBeVisible()
    // A newer published version must not grant the other learner access to the older snapshot.
    await page.getByLabel('英文标题', { exact: true }).fill(`${title} revised`)
    await page.getByLabel('正文', { exact: true }).fill('Every small step can begin a useful change.')
    await page.getByRole('button', { name: '保存草稿', exact: true }).click()
    await page.getByRole('button', { name: '发布新草稿', exact: true }).click()
    await page.getByRole('button', { name: '确认发布', exact: true }).click()
    await expect(page.getByRole('button', { name: '发布新草稿', exact: true })).toHaveCount(0)
    await other.goto(`/reading/${id}?version=${oldVersion}`)
    await expect(other.getByText('文章不存在或暂不可访问', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '下架文章', exact: true }).click()
    await page.getByRole('button', { name: '确认下架', exact: true }).click()
    await expect(page.getByRole('button', { name: '发布草稿', exact: true })).toBeVisible()
    await learner.goto('/reading')
    await learner.locator(`.reading-history a[href^="/reading/${id}?version=${oldVersion}"]`).click()
    await expect(learner.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await other.goto(`/reading/${id}`)
    await expect(other.getByText(/文章已下架，请从本人阅读历史继续/)).toBeVisible()
    await learner.goto('/notebook')
    const row = learner.locator('.notebook-word').filter({ has: learner.getByRole('button', { name: 'small', exact: true }) })
    await row.getByRole('button', { name: '取消收藏', exact: true }).click()
    await learner.getByRole('button', { name: '确认取消收藏', exact: true }).click()
    await expect(learner.getByRole('button', { name: 'small', exact: true })).toHaveCount(0)
    await learner.goto(`/reading/${id}?version=${oldVersion}`); await selectSmall(learner)
    const restored = learner.waitForResponse(response => response.url().endsWith('/vocabulary/words') && response.request().method() === 'POST')
    await learner.getByRole('dialog').getByRole('button', { name: '恢复收藏', exact: true }).click()
    expect(String((await (await restored).json()).word.id)).toBe(wordId)
    await expect(learner.getByRole('dialog').getByRole('button', { name: '已收藏', exact: true })).toBeDisabled()
    expect(await learner.evaluate(() => [Object.keys(localStorage), Object.keys(sessionStorage)])).toEqual([[], []])
  } finally { await context.close(); await otherContext.close() }
})
