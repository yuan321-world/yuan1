    await r.fulfill({json:{items:[{entryId:q==='app'?'e':'agenda',lemma:q==='app'?'apple':'agenda',partOfSpeech:'n.',definitionZh:q==='app'?'苹果':'议程'}]}}).catch(()=>{})
