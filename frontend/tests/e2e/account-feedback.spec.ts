test('network failure has one page recovery banner and does not resend an operation', async ({ page }) => {
  let sends = 0
  await page.route('**/api/v1/account/email-codes', route => { sends++; return route.abort() })
  await page.goto('/account')
  await page.getByLabel('当前密码（验证邮箱）', { exact: true }).fill('valid-password')
  await page.getByLabel('邮箱地址', { exact: true }).fill('reader@example.com')
  await page.getByRole('button', { name: '获取验证码', exact: true }).click()
  await expect(page.locator('.page-feedback')).toContainText('无法连接')
  await expect(page.locator('form .form-feedback')).toHaveCount(0)
  await page.getByRole('button', { name: '重新连接' }).click()
  await expect(page.locator('.page-feedback')).toHaveCount(0)
  await expect(page).toHaveURL('/account')
  expect(sends).toBe(1)
})

