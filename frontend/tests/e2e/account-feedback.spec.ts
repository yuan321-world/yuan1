import { expect, test } from '@playwright/test'
import { mockIdentity } from './identity-fixtures'

test.beforeEach(async ({ page }) => {
  await mockIdentity(page)
  await page.route('**/api/v1/auth/csrf', route => route.fulfill({ json: { token: 'mock', headerName: 'X-CSRF-TOKEN' } }))
})

test('binding password validation belongs below its field and clears only when resolved', async ({ page }) => {
  let sent = 0
  await page.route('**/api/v1/account/email-codes', route => { sent++; return route.fulfill({ status: 503, json: { code: 'EMAIL_UNAVAILABLE' } }) })
  await page.goto('/account')
  const form = page.locator('.account-email-form'), password = page.getByLabel('当前密码（验证邮箱）', { exact: true })
  await expect(form.getByRole('alert')).toHaveCount(0)
  await password.fill('bad')
  await page.getByLabel('邮箱地址', { exact: true }).fill('reader@example.com')
  await page.getByRole('button', { name: '获取验证码', exact: true }).click()
  await expect(password).toHaveAttribute('aria-invalid', 'true')
  await expect(password).toBeFocused()
  await expect(form.locator('#binding-current-password-error')).toBeVisible()
  await expect(page.locator('.account-page > .form-message')).toHaveCount(0)
  await password.fill('still')
  await expect(password).toHaveAttribute('aria-invalid', 'true')
  await password.fill('valid-password')
  await expect(password).not.toHaveAttribute('aria-invalid', 'true')
  expect(sent).toBe(0)
})

test('401 bad current password stays local and does not expire the session', async ({ page }) => {
  await page.route('**/api/v1/account/email-codes', route => route.fulfill({ status: 401, json: { code: 'BAD_CREDENTIALS', fieldErrors: { currentPassword: '请检查当前密码' } } }))
  await page.goto('/account')
  await page.getByLabel('当前密码（验证邮箱）', { exact: true }).fill('wrong-password')
  await page.getByLabel('邮箱地址', { exact: true }).fill('reader@example.com')
  await page.getByRole('button', { name: '获取验证码', exact: true }).click()
  await expect(page.locator('#binding-current-password-error')).toHaveText('请检查当前密码')
  await expect(page).toHaveURL('/account')
  await expect(page.locator('.account-grid .auth-field-error')).toHaveCount(0)
  await expect(page.getByLabel('当前密码（验证邮箱）', { exact: true })).toBeFocused()
})

test('password errors focus the first invalid field and confirmation reacts to password correction', async ({ page }) => {
  await page.goto('/account')
  await page.getByLabel('当前密码', { exact: true }).fill('valid-password')
  const password = page.getByLabel('新密码', { exact: true }), confirmation = page.getByLabel('确认新密码', { exact: true })
  await password.fill('bad')
  await confirmation.fill('different-password')
  await page.getByRole('button', { name: '更新密码' }).click()
  await expect(password).toBeFocused()
  await expect(password).toHaveAttribute('aria-invalid', 'true')
  await expect(confirmation).toHaveAttribute('aria-invalid', 'true')
  await password.fill('different-password')
  await expect(password).not.toHaveAttribute('aria-invalid', 'true')
  await expect(confirmation).not.toHaveAttribute('aria-invalid', 'true')
})

test('mail service failure stays inside its form and nickname success is a polite toast', async ({ page }) => {
  await page.route('**/api/v1/account/email-codes', route => route.fulfill({ status: 503, json: { code: 'EMAIL_UNAVAILABLE' } }))
  await page.route('**/api/v1/account/profile', route => route.fulfill({ json: { id: 'mock-identity', username: 'mock_learner', displayName: 'New name', roles: ['USER'] } }))
  await page.goto('/account')
  await page.getByLabel('当前密码（验证邮箱）', { exact: true }).fill('valid-password')
  await page.getByLabel('邮箱地址', { exact: true }).fill('reader@example.com')
  await page.getByRole('button', { name: '获取验证码', exact: true }).click()
  await expect(page.locator('.account-email-form .form-feedback')).toContainText('邮件服务暂不可用')
  await expect(page.locator('.account-grid .form-feedback')).toHaveCount(0)
  await page.getByLabel('昵称', { exact: true }).fill('New name')
  await page.getByRole('button', { name: '保存昵称' }).click()
  await expect(page.locator('.loop-toast[role="status"]')).toContainText('昵称已保存')
  await expect(page.locator('.account-email-form .form-feedback')).toContainText('邮件服务暂不可用')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

