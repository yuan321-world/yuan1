test('unfinished assisted phrase remains resumable after canceling its collection',async({page})=>{
  await page.locator('[data-tab="phrases"]').click()
  await page.locator('[data-join-phrase="look-forward-to"]').click()
  await page.locator('[data-practice-phrase="look-forward-to"]').click()
  await page.locator('#phrase-mode-write').click()
  await page.locator('#phrase-hint').click()
  await page.locator('#phrase-answer').fill('look forward to')
  await page.locator('#phrase-check').click()
  await expect(page.locator('#phrase-continue')).toHaveText('再试一次')
  await page.getByRole('button',{name:'关闭词组练习'}).click()
  await page.locator('[data-remove-phrase="look-forward-to"]').click()
  await page.reload()
  await page.locator('#resume-phrase').click()
  await page.locator('#phrase-continue').click()
  await page.locator('#phrase-answer').fill('look forward to')
  await page.locator('#phrase-check').click()
  await expect(page.locator('#phrase-practice')).toContainText('本次词组练习完成')
  const state=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)!),key)
  expect(state.phraseEvents).toHaveLength(1)
  expect(state.phraseEvents[0].independent).toBe(false)
  expect(state.phraseEvents[0].assisted).toBe(true)
  expect(state.phrases.find((p:{id:string})=>p.id==='look-forward-to').saved).toBe(false)
  expect(state.events).toHaveLength(0)
})

test('manual phrase editing preserves identity and source without network calls',async({page})=>{
  const apiCalls:string[]=[]
  page.on('request',r=>{if(r.url().includes('/api/'))apiCalls.push(r.url())})
  await page.locator('[data-tab="phrases"]').click()
  await page.locator('#add-phrase').click()
  await page.locator('#phrase-text').fill('on purpose')
  await page.locator('#phrase-meaning').fill('故意地')
  await page.locator('#phrase-save').click()
  await expect(page.locator('[data-detail-phrase]')).toHaveCount(4)
  await page.getByRole('button',{name:'on purpose',exact:true}).click()
  await expect(page.locator('#library-drawer')).toContainText('手动收藏 · 个人输入')
  await page.locator('#edit-phrase').click()
  await expect(page.locator('#phrase-text')).toHaveAttribute('readonly','')
  await page.locator('#phrase-meaning').fill('有意地；故意地')
  await page.locator('#phrase-note').fill('与 by accident 对照记忆。')
  await page.locator('#phrase-save').click()
  await page.reload()
  await page.getByRole('button',{name:'on purpose',exact:true}).click()
  await expect(page.locator('#library-drawer')).toContainText('有意地；故意地')
  await expect(page.locator('#library-drawer')).toContainText('与 by accident 对照记忆。')
  expect(apiCalls).toEqual([])
})
