import { test, expect, type Page } from '@playwright/test'

const url = 'http://127.0.0.1:4187/vocabulary-upgrade-preview.html'
const key = 'lingua-vocabulary-prototype-20261102-v1'
async function chooseBook(page: Page, id: string) {
  await page.locator('#book').click()
  await page.locator(`[data-book="${id}"]`).click()
}

test.beforeEach(async ({ page }) => { await page.goto(url) })

test('plan, scope and local persistence without network writes', async ({ page }, info) => {
  const calls: string[] = []
  page.on('request', r => { if (r.url().includes('/api/')) calls.push(r.url()) })
  await page.locator('#plan-open').click()
  await page.getByRole('button', { name: '悠闲' }).click()
  await page.locator('#auto-next').uncheck()
  await page.locator('#save-plan').click()
  await expect(page.locator('.plan-strip')).toContainText('每天新学 5 词')
  await page.locator('#book').click()
  await expect(page.locator('[data-book="cet4"]')).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: `../.tool-cache/vocabulary-prototype/${info.project.name}-book-picker.png`, fullPage: true })
  await page.setViewportSize({ width: 320, height: 740 })
  expect(await page.locator('#books').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await page.setViewportSize(info.project.use.viewport!)
  await chooseBook(page, 'personal')
  await expect(page.locator('.progress-label')).toContainText('2 / 5')
  await page.reload()
  await expect(page.locator('#book')).toContainText('我的生词')
  await expect(page.locator('.plan-strip')).toContainText('悠闲计划')
  await page.locator('#plan-open').click()
  await expect(page.locator('#auto-next')).not.toBeChecked()
  await page.getByRole('button', { name: '关闭学习计划' }).click()
  expect(calls).toEqual([])
})

test('copy continuously advances and shows meanings only at round end', async ({ page }, info) => {
  await page.locator('#plan-open').click()
  await page.locator('#auto-next').uncheck()
  await page.locator('#save-plan').click()
  await page.locator('#start-new').click()
  await page.locator('#spelling').click()
  await expect(page.locator('#hint')).toHaveCount(0)
  await expect(page.locator('.study-card')).not.toContainText('进步；进展')
  await page.screenshot({ path: `../.tool-cache/vocabulary-prototype/${info.project.name}-copy.png`, fullPage: true })
  await page.locator('#answer').fill('prx')
  await expect(page.locator('#answer')).toHaveValue('pr')
  await page.reload()
  await page.locator('#resume').click()
  await expect(page.locator('#answer')).toHaveValue('pr')
  await page.locator('#answer').fill('progress')
  await expect(page.locator('#ghost')).toHaveText('remember')
  await expect(page.locator('#next')).toHaveCount(0)
  await page.locator('#answer').fill('remember')
  await page.locator('#answer').fill('important')
  await expect(page.locator('#ghost')).toHaveText('progress')
  await page.locator('#answer').fill('progress')
  await expect(page.locator('.completed')).toContainText('这一轮，完成了')
  await expect(page.locator('.round-details')).toContainText('进步；进展')
  await expect(page.locator('.round-details')).toContainText('Regular practice helps')
  await page.screenshot({ path: `../.tool-cache/vocabulary-prototype/${info.project.name}-round-complete.png`, fullPage: true })
  const state = await page.evaluate(k => JSON.parse(localStorage.getItem(k)!), key)
  expect(state.events).toHaveLength(3)
  expect(state.events.every((e: { independent: boolean }) => !e.independent)).toBe(true)
  expect(state.events.find((e: { id: string }) => e.id === 'progress').assisted).toBe(true)
  await page.locator('#done').click()
  await chooseBook(page, 'personal')
  await expect(page.locator('.progress-label')).toContainText('3 / 5')
})

test('review hides words, unknown requeues and clean recall records separately', async ({ page }) => {
  await page.locator('#plan-open').click()
  await page.locator('#auto-next').uncheck()
  await page.locator('#save-plan').click()
  await page.locator('#start-review').click()
  await page.locator('#spelling').click()
  await expect(page.locator('.study-card')).not.toContainText('study')
  await expect(page.locator('.queue')).not.toContainText('library')
  await page.locator('#unknown').click()
  await expect(page.locator('.word')).toHaveText('study')
  await expect(page.locator('.queue')).not.toContainText('library')
  await page.locator('#next').click()
  await page.locator('#answer').fill('library')
  await page.locator('#next').click()
  await page.locator('#answer').fill('study')
  await page.locator('#next').click()
  const state = await page.evaluate(k => JSON.parse(localStorage.getItem(k)!), key)
  expect(state.events.filter((e: { independent: boolean }) => e.independent)).toHaveLength(1)
  expect(state.mastery.study.stage).toBe(1)
  expect(state.mastery.library.stage).toBe(2)
})

