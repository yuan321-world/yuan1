test('recognition always waits for next, even with auto advance enabled', async ({ page }) => {
  for (const kind of ['new', 'review']) {
    await page.locator('#reset').click()
    await page.locator(`#start-${kind}`).click()
    await page.locator('#recognition').click()
    const word = await page.locator('.word').textContent()
    await page.locator('#know').click()
    await page.waitForTimeout(2100)
    await expect(page.locator('.word')).toHaveText(word!)
    await expect(page.locator('#study-auto')).toHaveCount(0)
    await page.locator('#next').click()
    await expect(page.locator('.word')).not.toHaveText(word!)
    await page.locator('#pause').click()
  }
})

